# pylint: disable-next=too-many-instance-attributes
class ProteinContext:
    r"""Singleton for protein pdb strucutres validation"""

    # pylint: disable-next=too-many-arguments,too-many-locals
    def __init__(
        self,
        impurities: Optional[list] = DEFAULT_IMPURITIES,
    ):
        self.impurities = impurities

    @staticmethod
    def get_current() -> "ProteinContext":
        r"""Get or create a singleton context."""

        # pylint: disable-next=global-statement
        global _default_glide_context

        if _default_glide_context is None:
            _default_glide_context = ProteinContext(impurities=DEFAULT_IMPURITIES)
        return _default_glide_context

    @staticmethod
    def set_current(context: "ProteinContext") -> None:
        """Set the current context."""
        global _default_glide_context
        _default_glide_context = context
